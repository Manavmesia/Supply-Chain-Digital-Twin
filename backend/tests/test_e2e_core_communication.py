class TestCoreAgentCommunicationAndDataAccuracy:
    """Verifies precise data payload contracts and communication between agents."""

    @pytest.mark.asyncio
    async def test_order_management_to_inventory_data_transfer(self):
        """
        Verify ADS-01 correctly populates state['order'] and state['customer']
        and that ADS-03 consumes exact product_ids and quantities from it.
        """
        from app.agents.operational.inventory import InventoryAgent
        from app.agents.operational.order_management import OrderManagementAgent

        customer_id = uuid.uuid4()
        product_id = uuid.uuid4()

        cust = SimpleCustomer(customer_id, "Test Enterprise")
        prod = SimpleProduct(product_id, "Enterprise Server", "SRV-001", Decimal("1500.00"))

        session_om = AsyncMock()
        session_om.execute = AsyncMock(side_effect=[_mock_scalar(cust), _mock_scalar(prod)])
        session_om.flush = AsyncMock()

        state: SupplyChainState = {
            "workflow_id": str(uuid.uuid4()),
            "correlation_id": str(uuid.uuid4()),
            "workflow_status": "received",
            "active_agents": [],
            "order": {
                "customer_id": str(customer_id),
                "items": [{"product_id": str(product_id), "quantity": 4}],
                "priority": "high",
            },
        }

        om_agent = OrderManagementAgent(session=session_om)
        om_result = await om_agent.run(state)

        state.update(om_result)

        # Verify data generated by Order Management
        assert state["order"]["customer_id"] == str(customer_id)
        assert state["order"]["priority"] == "high"
        assert state["order"]["total_amount"] == "6000.00"  # 4 * 1500.00
        assert len(state["order"]["items"]) == 1
        assert state["order"]["items"][0]["product_id"] == str(product_id)
        assert state["order"]["items"][0]["quantity"] == 4
        assert state["customer"]["name"] == "Test Enterprise"

        # 2. Run Inventory Agent with state populated by Order Management
        wh_id = uuid.uuid4()
        inv_record = MagicMock(
            inventory_id=uuid.uuid4(),
            product_id=product_id,
            warehouse_id=wh_id,
            available_qty=50,
            reserved_qty=5,
            safety_stock=10,
        )
        inv_after = MagicMock(
            inventory_id=inv_record.inventory_id,
            product_id=product_id,
            warehouse_id=wh_id,
            available_qty=50,
            reserved_qty=9,  # 5 + 4
            safety_stock=10,
        )

        session_inv = AsyncMock()
        session_inv.execute = AsyncMock(side_effect=[
            _mock_scalars([inv_record]),
            MagicMock(),
            _mock_scalar(inv_after),
        ])
        session_inv.flush = AsyncMock()

        inv_agent = InventoryAgent(session=session_inv)
        inv_result = await inv_agent.run(state)

        # Verify Inventory Agent accurately received data from state['order']
        assert inv_result["next_node"] == "warehouse"
        assert str(product_id) in inv_result["inventory"]
        assert inv_result["inventory"][str(product_id)]["status"] == "reserved"
        assert inv_result["inventory"][str(product_id)]["reserved_qty"] == 4
        assert inv_result["inventory"][str(product_id)]["warehouse_id"] == str(wh_id)

    @pytest.mark.asyncio
    async def test_inventory_to_supplier_out_of_stock_data_transfer(self):
        """
        Verify that when ADS-03 detects out-of-stock items, it correctly flags them in state,
        and ADS-05 receives the exact out-of-stock product_id and needed quantity.
        """
        from app.agents.operational.inventory import InventoryAgent
        from app.agents.operational.supplier import SupplierAgent

        product_id = uuid.uuid4()
        order_id = str(uuid.uuid4())
        workflow_id = str(uuid.uuid4())

        state: SupplyChainState = {
            "workflow_id": workflow_id,
            "correlation_id": str(uuid.uuid4()),
            "workflow_status": "operational",
            "active_agents": ["ADS-01"],
            "warehouse": {"warehouse_id": str(uuid.uuid4())},
            "order": {
                "order_id": order_id,
                "customer_id": str(uuid.uuid4()),
                "items": [{"product_id": str(product_id), "quantity": 25}],
                "priority": "standard",
            },
        }

        # 1. Inventory Agent detects no stock
        session_inv = AsyncMock()
        session_inv.execute = AsyncMock(return_value=_mock_scalars([]))

        inv_agent = InventoryAgent(session=session_inv)
        inv_result = await inv_agent.run(state)

        state.update(inv_result)
        assert state["next_node"] == "supplier"
        assert state["inventory"][str(product_id)]["status"] == "out_of_stock"
        assert state["inventory"][str(product_id)]["needed"] == 25

        # 2. Supplier Agent receives state and creates PurchaseOrder with correct quantity
        supplier = MagicMock(
            supplier_id=uuid.uuid4(),
            name="Global Chips Ltd",
            lead_time_days=4,
            reliability_score=Decimal("96.0"),
            status="active",
        )
        supplier_prod = MagicMock(
            supplier_id=supplier.supplier_id,
            product_id=product_id,
            contract_price=Decimal("120.00"),
            minimum_order_qty=10,
        )

        session_sup = AsyncMock()
        pair_res = MagicMock()
        pair_res.all.return_value = [(supplier_prod, supplier)]
        session_sup.execute = AsyncMock(return_value=pair_res)
        session_sup.flush = AsyncMock()
        session_sup.add = MagicMock()

        sup_agent = SupplierAgent(session=session_sup)
        sup_result = await sup_agent.run(state)

        state.update(sup_result)

        # Verify Supplier Agent created PO with accurate data
        assert state["supplier"]["status"] == "selected"
        po = state["supplier"]["purchase_orders"][0]
        assert po["supplier_id"] == str(supplier.supplier_id)
        assert po["product_id"] == str(product_id)
        assert po["quantity"] == 25
        assert po["unit_cost"] == "120.00"

    @pytest.mark.asyncio
    async def test_warehouse_and_transportation_to_ceo_data_transfer(self):
        """
        Verify ADS-04 (Warehouse) and ADS-06 (Transportation) pass city, carrier,
        freight mode, tracking ID, and total cost down to ADS-17 (CEO Agent).
        """
        from app.agents.operational.transportation import TransportationAgent
        from app.agents.operational.warehouse import WarehouseAgent
        from app.agents.coordination.ceo import CEOAgent

        order_id = str(uuid.uuid4())
        wh_id = str(uuid.uuid4())

        state: SupplyChainState = {
            "workflow_id": str(uuid.uuid4()),
            "correlation_id": str(uuid.uuid4()),
            "workflow_status": "operational",
            "active_agents": ["ADS-01", "ADS-03"],
            "order": {
                "order_id": order_id,
                "status": "pending",
                "priority": "critical",
                "total_amount": "45000.00",
                "items": [{"product_id": str(uuid.uuid4()), "quantity": 10}],
            },
            "inventory": {
                str(uuid.uuid4()): {
                    "status": "reserved",
                    "warehouse_id": wh_id,
                    "reserved_qty": 10,
                }
            },
        }

        # 1. Warehouse Agent execution
        wh_obj = SimpleWarehouse(uuid.UUID(wh_id), "WH-WEST-01", "Los Angeles", "US")
        session_wh = AsyncMock()
        session_wh.execute = AsyncMock(side_effect=[
            _mock_scalar(wh_obj),
            MagicMock(),
            MagicMock(),
        ])
        session_wh.flush = AsyncMock()

        wh_agent = WarehouseAgent(session=session_wh)
        wh_result = await wh_agent.run(state)
        state.update(wh_result)

        assert state["warehouse"]["city"] == "Los Angeles"
        assert state["warehouse"]["country"] == "US"
        assert state["order"]["status"] == "warehouse_assigned"

        # 2. Transportation Agent execution
        carrier_air = SimpleCarrier(uuid.uuid4(), "DHL Express", "DHL", Decimal("98.0"), "active", ["air", "road"])
        route_air = MagicMock(
            route_id=uuid.uuid4(),
            carrier_id=carrier_air.carrier_id,
            origin_location="Los Angeles, US",
            destination="Rotterdam, NL",
            freight_mode="air",
            transit_days=1,
            base_cost=Decimal("6500.00"),
            is_active=True,
        )

        session_tr = AsyncMock()
        session_tr.execute = AsyncMock(side_effect=[
            _mock_scalars([carrier_air]),
            _mock_scalars([route_air]),
            MagicMock(),
        ])
        session_tr.flush = AsyncMock()
        session_tr.add = MagicMock()

        tr_agent = TransportationAgent(session=session_tr)
        tr_result = await tr_agent.run(state)
        state.update(tr_result)

        assert state["shipment"]["carrier"] == "DHL Express"
        assert state["shipment"]["freight_mode"] == "air"
        assert state["shipment"]["transit_days"] == 1
        assert state["order"]["status"] == "in_transit"

        # 3. CEO Agent execution
        session_ceo = AsyncMock()
        session_ceo.execute = AsyncMock(return_value=MagicMock())
        session_ceo.flush = AsyncMock()

        ceo_agent = CEOAgent(session=session_ceo)
        ceo_result = await ceo_agent.run(state)
        state.update(ceo_result)

        assert state["executive_decision"]["approved"] is True
        assert state["executive_decision"]["approval_tier"] == "finance_review"
        assert state["order"]["status"] == "delivered"
        assert state["workflow_status"] == "completed"
        assert state["active_agents"] == ["ADS-01", "ADS-03", "ADS-04", "ADS-06", "ADS-17"]
