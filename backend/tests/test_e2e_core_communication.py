"""
Verification test suite for Core Agent Communication and Data Accuracy — Phase 3 MVP.

Specifically verifies:
  1. ADS-01 (Order Management) → ADS-03 (Inventory): Order details, item list, quantities, and customer data transferred accurately.
  2. ADS-03 (Inventory) → ADS-05 (Supplier): Out-of-stock product IDs and needed quantities transferred accurately to generate PurchaseOrders.
  3. ADS-04 (Warehouse) / ADS-05 (Supplier) → ADS-06 (Transportation): Origin warehouse location and shipment requirements passed correctly to select carrier & route.
  4. ADS-06 (Transportation) → ADS-17 (CEO): Total order amount, priority, shipment details, and risk flags transferred accurately for policy enforcement.
  5. End-to-end full graph state snapshot immutability & data integrity.
"""

from __future__ import annotations

import uuid
from decimal import Decimal
from unittest.mock import AsyncMock, MagicMock

import pytest

from app.graph.state import SupplyChainState


class SimpleCustomer:
    def __init__(self, customer_id, name, customer_tier="enterprise", is_active=True):
        self.customer_id = customer_id
        self.name = name
        self.customer_tier = customer_tier
        self.is_active = is_active


class SimpleProduct:
    def __init__(self, product_id, name, sku, unit_price, active=True):
        self.product_id = product_id
        self.name = name
        self.sku = sku
        self.unit_price = unit_price
        self.active = active


class SimpleWarehouse:
    def __init__(self, warehouse_id, name, city="Los Angeles", country="US", capacity_units=50000, current_load=2000, status="active"):
        self.warehouse_id = warehouse_id
        self.name = name
        self.city = city
        self.country = country
        self.location = f"{city}, {country}"
        self.capacity_units = capacity_units
        self.current_load = current_load
        self.status = status


class SimpleCarrier:
    def __init__(self, carrier_id, name, code="FEDEX", reliability_score=Decimal("98.0"), status="active", freight_modes=None):
        self.carrier_id = carrier_id
        self.name = name
        self.code = code
        self.reliability_score = reliability_score
        self.status = status
        self.freight_modes = freight_modes or ["air", "road"]


def _mock_scalar(value):
    result = MagicMock()
    result.scalar_one_or_none.return_value = value
    result.scalars.return_value.all.return_value = [value] if value is not None else []
    result.all.return_value = [(value, value)] if value else []
    return result


def _mock_scalars(values: list):
    result = MagicMock()
    result.scalars.return_value.all.return_value = values
    result.scalar_one_or_none.return_value = values[0] if values else None
    result.all.return_value = [(v, v) for v in values]
    return result


