"""
Reports REST API — Phase 4

GET /api/v1/reports
    List historical generated reports.

GET /api/v1/reports/{report_id}
    Get detailed summary & KPI snapshot for a specific report.
"""

from __future__ import annotations

import uuid
from typing import Any

import structlog
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db_session
from app.repositories.report import ReportRepository

logger = structlog.get_logger(__name__)
router = APIRouter(prefix="/reports", tags=["reports"])


@router.get(
    "",
    summary="List generated reports",
)
async def list_reports(
    skip: int = Query(0, ge=0),
    limit: int = Query(20, ge=1, le=100),
    status_filter: str | None = Query(None, alias="status"),
    session: AsyncSession = Depends(get_db_session),
) -> dict[str, Any]:
    """Fetch paginated immutable reports generated by the digital twin."""
    repo = ReportRepository(session)
    filters = {}
    if status_filter:
        filters["status"] = status_filter

    reports = await repo.get_multi(skip=skip, limit=limit, filters=filters)
    total = await repo.count(filters=filters)

    return {
        "items": [
            {
                "report_id": str(r.report_id),
                "report_type": r.report_type,
                "title": r.title,
                "status": r.status,
                "workflow_id": str(r.workflow_id) if r.workflow_id else None,
                "created_at": r.created_at.isoformat() if r.created_at else None,
                "payload_summary": r.payload_summary,
            }
            for r in reports
        ],
        "total": total,
        "skip": skip,
        "limit": limit,
    }


@router.get(
    "/{report_id}",
    summary="Get report by ID",
)
async def get_report_by_id(
    report_id: uuid.UUID,
    session: AsyncSession = Depends(get_db_session),
) -> dict[str, Any]:
    """Fetch specific report details and payload summary."""
    repo = ReportRepository(session)
    report = await repo.get_by_id(report_id)

    if report is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Report '{report_id}' not found",
        )

    return {
        "report_id": str(report.report_id),
        "report_type": report.report_type,
        "title": report.title,
        "status": report.status,
        "workflow_id": str(report.workflow_id) if report.workflow_id else None,
        "generated_by_agent": report.generated_by_agent,
        "created_at": report.created_at.isoformat() if report.created_at else None,
        "payload_summary": report.payload_summary,
    }
