"""Repository for PricingHistory domain queries."""

import uuid
from collections.abc import Sequence

from app.models.pricing_history import PricingHistory
from app.repositories.base import BaseRepository
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession


class PricingHistoryRepository(BaseRepository[PricingHistory]):
    def __init__(self, session: AsyncSession) -> None:
        super().__init__(PricingHistory, session)

    async def get_latest_by_product(
        self, product_id: uuid.UUID
    ) -> PricingHistory | None:
        """Return the most recently created pricing record for a product.

        Used by the Pricing Agent to understand the current effective price
        before computing a new recommendation.
        """
        query = (
            select(PricingHistory)
            .where(PricingHistory.product_id == product_id)
            .order_by(PricingHistory.created_at.desc())
            .limit(1)
        )
        result = await self.session.execute(query)
        return result.scalar_one_or_none()

    async def get_pending_approval(self) -> Sequence[PricingHistory]:
        """Return all pricing recommendations where approved_price is still NULL.

        These are records that have been generated by the Pricing Agent but
        have not yet been reviewed or applied.
        """
        query = (
            select(PricingHistory)
            .where(PricingHistory.approved_price.is_(None))
            .order_by(PricingHistory.created_at.asc())
        )
        result = await self.session.execute(query)
        return result.scalars().all()
